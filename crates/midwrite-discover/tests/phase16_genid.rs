/// The ```json blocks of the appendix whose text is an invariant
/// declaration (an object with `name` and `property`).
fn templates() -> Vec<serde_json::Value> {
    let doc = std::fs::read_to_string(repo().join("docs/phase16/GENERATED-ID-INVARIANTS.md"))
        .expect("the design note");
    let appendix = doc
        .split_once("## Appendix: contract templates")
        .expect("the appendix")
        .1;
    let mut out = Vec::new();
    let mut rest = appendix;
    while let Some((_, after)) = rest.split_once("```json\n") {
        let (block, tail) = after.split_once("```").expect("a closed block");
        let v: serde_json::Value = serde_json::from_str(block)
            .unwrap_or_else(|e| panic!("a template that parses: {e}\n{block}"));
        if v.get("property").is_some() {
            out.push(v);
        }
        rest = tail;
    }
    out
}

/// The fixture entry a midday selector of the templates corresponds to.
fn fixture_entry(selector: &str) -> &'static str {
    match selector.rsplit_once('#').map(|(_, e)| e) {
        Some("leaveTeam") => "src/services/teams.ts#leaveTeam",
        Some("deleteTeamMember") => "src/services/teams.ts#deleteTeamMember",
        Some(e) if e.starts_with("GenerateInsightsProcessor") => {
            "src/services/insights.ts#generateTeamInsights"
        }
        other => panic!("no fixture entry for {other:?}"),
    }
}

#[test]
fn every_contract_template_parses_and_loads_against_the_first_party_application() {
    let all = templates();
    assert!(all.len() >= 4, "templates found: {}", all.len());
    let tmp =
        std::env::temp_dir().join(format!("midwrite-phase16-templates-{}", std::process::id()));
    std::fs::create_dir_all(&tmp).unwrap();
    for t in all {
        let name = t["name"].as_str().unwrap().to_owned();
        // The template as a developer would paste it, entries pointed at
        // the fixture's midday-shaped code.
        let mut declared = t.clone();
        let entries: Vec<serde_json::Value> = t["entries"]
            .as_array()
            .expect("entries")
            .iter()
            .map(|e| serde_json::Value::from(fixture_entry(e.as_str().unwrap())))
            .collect();
        declared["entries"] = serde_json::Value::Array(entries.clone());
        let contracts = serde_json::json!({
            "schemaVersion": 1,
            "kind": "midwrite.contracts",
            "description": "a Phase 16 template under test",
            "invariants": [declared]
        });
        midwrite_discover::contracts::Contracts::parse(&contracts.to_string())
            .unwrap_or_else(|e| panic!("`{name}` parses as a contract: {e}"));
        let path = tmp.join(format!("{name}.json"));
        std::fs::write(&path, contracts.to_string()).unwrap();
        for entry in entries {
            let entry = entry.as_str().unwrap();
            let r = discover(
                &repo().join(APP),
                &Options {
                    contracts: Some(path.clone()),
                    entries: vec![format!("#{}", entry.rsplit_once('#').unwrap().1)],
                    ..options()
                },
            )
            .expect("discovery runs");
            // The declared property is attached to a candidate, its scenario
            // loads (the loader validates the formula against the model)
            // and it is model-checked.
            let with: Vec<&CandidateReport> = r
                .candidates
                .iter()
                .filter(|c| c.candidate.properties.iter().any(|p| p.name == name))
                .collect();
            assert!(
                !with.is_empty(),
                "`{name}` attaches to a candidate of `{entry}`"
            );
            for c in with {
                // Loaded (the loader validated the formula against the
                // model) and explored to a verdict.
                let checked = c.scenarios.iter().any(|s| {
                    s.model.as_ref().is_some_and(|m| {
                        m.verdict == "COUNTEREXAMPLE_FOUND"
                            || m.verdict == "NO_COUNTEREXAMPLE_WITHIN_BOUNDS"
                    }) && s.invariants.iter().any(|i| i.name == name)
                });
                // A row-count template (`atLeast`) is instantiated per group
                // of the synthesized rows; a group the synthesized state
                // already violates is not checked, and says so.
                let not_instantiable = t["property"]["template"] == "atLeast"
                    && c.scenarios.iter().all(|s| {
                        s.invariant_notes.iter().any(|n| {
                            n.starts_with(&format!("`{name}`: group"))
                                && n.ends_with(
                                    "violates the invariant in the initial state; not checked",
                                )
                        })
                    });
                assert!(
                    checked || not_instantiable,
                    "`{name}` on `{entry}` is model-checked: {} {} {:?}",
                    c.status,
                    c.finding,
                    c.scenarios
                        .iter()
                        .map(|s| (&s.synthesis.status, &s.invariant_notes))
                        .collect::<Vec<_>>()
                );
                if t["property"]["template"] == "formula" {
                    assert!(
                        checked,
                        "a `formula` template is loaded and checked: `{name}`"
                    );
                }
            }
        }
    }
    let _ = std::fs::remove_dir_all(&tmp);
}
