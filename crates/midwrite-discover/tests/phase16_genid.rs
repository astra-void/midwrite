//! Phase 16: discovery with properties over generated identifiers, on the
//! first-party application `fixtures/phase16/genid`
//! (`docs/phase16/GENERATED-ID-INVARIANTS.md`), and the contract templates
//! of that document, loaded against the same application.

use std::path::PathBuf;

use midwrite_discover::pipeline::{Options, discover};
use midwrite_discover::report::{CandidateReport, DiscoveryReport};

const APP: &str = "fixtures/phase16/genid";

fn repo() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..")
}

fn options() -> Options {
    Options {
        model_check: true,
        include_timing: false,
        tool_version: "test".to_owned(),
        ..Options::default()
    }
}

fn run(entry: &str, opts: Options) -> DiscoveryReport {
    discover(
        &repo().join(APP),
        &Options {
            entries: vec![entry.to_owned()],
            ..opts
        },
    )
    .expect("discovery runs")
}

/// The candidate of `class` (`return-value`, `read-modify-write`, ...).
fn of_class<'a>(r: &'a DiscoveryReport, class: &str) -> &'a CandidateReport {
    r.candidates
        .iter()
        .find(|c| {
            serde_json::to_value(c.candidate.class)
                .ok()
                .and_then(|v| v.as_str().map(str::to_owned))
                .as_deref()
                == Some(class)
        })
        .unwrap_or_else(|| {
            panic!(
                "a `{class}` candidate among {:?}",
                r.candidates
                    .iter()
                    .map(|c| (&c.candidate.title, &c.status))
                    .collect::<Vec<_>>()
            )
        })
}

fn violated(c: &CandidateReport) -> Vec<String> {
    c.scenarios
        .iter()
        .filter_map(|s| s.model.as_ref().and_then(|m| m.violated.clone()))
        .collect()
}

#[test]
fn concurrent_first_calls_tell_a_caller_a_token_that_is_not_stored() {
    let r = run("#ensureShareToken", options());
    let declared = of_class(&r, "return-value");
    assert_eq!(
        declared.status, "MODEL_COUNTEREXAMPLE",
        "{}",
        declared.finding
    );
    assert!(violated(declared).contains(&"share-token-told-is-stored".to_owned()));
    let p = &declared.candidate.properties[0];
    assert_eq!(p.origin.as_str(), "USER_DECLARED");
    // The read-modify-write candidate carries the declared property too.
    let rmw = of_class(&r, "read-modify-write");
    assert_eq!(rmw.status, "MODEL_COUNTEREXAMPLE", "{}", rmw.finding);
}

/// The `description` of the emitted scenarios' invariant `name`.
fn emitted_descriptions(dir: &std::path::Path, name: &str) -> Vec<String> {
    let mut out = Vec::new();
    for e in std::fs::read_dir(dir)
        .expect("the emitted scenarios")
        .flatten()
    {
        let Ok(doc) = serde_json::from_str::<serde_json::Value>(
            &std::fs::read_to_string(e.path()).unwrap_or_default(),
        ) else {
            continue;
        };
        for i in doc["invariants"].as_array().into_iter().flatten() {
            if i["name"] == name {
                out.push(i["description"].as_str().unwrap_or_default().to_owned());
            }
        }
    }
    out
}

fn emit_dir(tag: &str) -> PathBuf {
    let dir = std::env::temp_dir().join(format!("midwrite-phase16-{tag}-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).unwrap();
    dir
}

/// An empty contracts file: nothing declared. One file per test (`tag`):
/// tests run in parallel threads of one process.
fn undeclared(tag: &str) -> PathBuf {
    let path = std::env::temp_dir().join(format!(
        "midwrite-phase16-undeclared-{tag}-{}.json",
        std::process::id()
    ));
    std::fs::write(
        &path,
        r#"{"schemaVersion": 1, "kind": "midwrite.contracts", "description": "nothing declared"}"#,
    )
    .unwrap();
    path
}

#[test]
fn without_a_declaration_the_serial_outcome_is_stated_over_generated_identity_and_holds() {
    // The heuristic serial-outcome property of midday's portal shape: every
    // serial outcome of the token is a value some caller generated. It is
    // now stated (generated by the same actor and generator) instead of
    // being refused, and it holds: every final token is one a caller
    // generated. Only a declared property about what callers are told sees
    // the defect.
    let dir = emit_dir("token");
    let r = run(
        "#ensureShareToken",
        Options {
            contracts: Some(undeclared("serial")),
            emit_dir: Some(dir.clone()),
            ..options()
        },
    );
    let rmw = of_class(&r, "read-modify-write");
    assert_eq!(rmw.status, "NO_VIOLATION_WITHIN_BOUNDS", "{}", rmw.finding);
    let inv = &rmw.scenarios[0].invariants[0];
    assert_eq!(inv.origin, "HEURISTIC_HYPOTHESIS");
    assert!(inv.formula.contains("GeneratedBy"), "{}", inv.formula);
    assert!(
        inv.formula.contains("Actor(\"ensureShareToken-1\")"),
        "{}",
        inv.formula
    );
    assert!(rmw.scenarios[0].invariant_notes.is_empty());
    let descriptions = emitted_descriptions(&dir, &inv.name);
    assert!(!descriptions.is_empty());
    assert!(
        descriptions.iter().all(|d| d.contains("never by its text")),
        "{descriptions:?}"
    );
    let _ = std::fs::remove_dir_all(&dir);
}

