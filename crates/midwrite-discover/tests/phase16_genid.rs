#[test]
fn a_resubmission_told_a_fresh_id_instead_of_the_stored_row_id_is_reported() {
    // Two submissions of one request: the second is told an id no row has
    // (the stored row's id was generated by the first).
    let r = run("#createProject", options());
    let c = of_class(&r, "return-value");
    assert_eq!(c.status, "MODEL_COUNTEREXAMPLE", "{}", c.finding);
    assert!(violated(c).contains(&"returned-project-id-is-the-request-row".to_owned()));
    // One request, a crash before the response and the client's resubmission.
    let c = of_class(&r, "resubmitted-write");
    assert_eq!(c.status, "MODEL_COUNTEREXAMPLE", "{}", c.finding);
    assert!(violated(c).contains(&"returned-project-id-is-the-request-row".to_owned()));
    // The upsert returns the stored row's id, generated by whichever attempt
    // created it.
    let r = run("#createProjectSafe", options());
    for class in ["return-value", "resubmitted-write"] {
        let c = of_class(&r, class);
        assert_eq!(
            c.status, "NO_VIOLATION_WITHIN_BOUNDS",
            "{class}: {}",
            c.finding
        );
    }
}

