import { boolean, index, integer, pgTable, serial, text, uuid } from "drizzle-orm/pg-core";

import { accounts } from "./accounts.js";

export type PaymentIntentStatus = "requires_payment" | "succeeded" | "canceled";

// payment_intent_id points at the order's current payment intent (no
// foreign key: the intent row is created by the same request).
export const orders = pgTable("orders", {
  id: serial("id").primaryKey(),
  accountId: uuid("account_id")
    .notNull()
    .references(() => accounts.id),
  totalCents: integer("total_cents").notNull(),
  paymentIntentId: text("payment_intent_id"),
});

// Payment intents: the id is generated by the application (src/lib/ids.ts).
// order_id is indexed, NOT unique.
export const paymentIntents = pgTable(
  "payment_intents",
  {
    id: text("id").primaryKey(),
    orderId: integer("order_id")
      .notNull()
      .references(() => orders.id),
    amountCents: integer("amount_cents").notNull(),
    status: text("status").$type<PaymentIntentStatus>().notNull().default("requires_payment"),
  },
  (t) => [index("payment_intents_order").on(t.orderId)],
);

export const stockLevels = pgTable("stock_levels", {
  sku: text("sku").primaryKey(),
  available: integer("available").notNull(),
});

export const reservations = pgTable("reservations", {
  id: serial("id").primaryKey(),
  sku: text("sku")
    .notNull()
    .references(() => stockLevels.sku),
  orderId: integer("order_id")
    .notNull()
    .references(() => orders.id),
  quantity: integer("quantity").notNull(),
});

// Single-use coupons.
export const coupons = pgTable("coupons", {
  id: serial("id").primaryKey(),
  code: text("code").notNull().unique(),
  percentOff: integer("percent_off").notNull(),
  redeemed: boolean("redeemed").notNull().default(false),
});

// coupon_id is indexed, NOT unique.
export const couponRedemptions = pgTable(
  "coupon_redemptions",
  {
    id: serial("id").primaryKey(),
    couponId: integer("coupon_id")
      .notNull()
      .references(() => coupons.id),
    accountId: uuid("account_id")
      .notNull()
      .references(() => accounts.id),
  },
  (t) => [index("coupon_redemptions_coupon").on(t.couponId)],
);
